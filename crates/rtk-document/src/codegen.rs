struct Gen {
    raw: Vec<String>,
    imports: BTreeSet<&'static str>,
}

impl Gen {
    /// A placeholder statement for `code`, kept verbatim.
    fn raw(&mut self, code: &str) -> TokenStream {
        let index = Literal::usize_unsuffixed(self.raw.len());
        self.raw.push(code.to_owned());
        quote!(__rtk_raw!(#index);)
    }

    fn import(&mut self, name: &'static str) -> TokenStream {
        self.imports.insert(name);
        let ident = format_ident!("{name}");
        quote!(#ident)
    }

    fn block(&mut self, ui: &str, nodes: &[Node]) -> TokenStream {
        let stmts: Vec<_> = nodes.iter().map(|node| self.node(ui, node)).collect();
        quote!(#(#stmts)*)
    }

    /// `|ui| { … }`, with the parameter named `_ui` when the body is empty
    /// (no unused variable warning).
    fn closure(&mut self, param: &str, nodes: &[Node]) -> TokenStream {
        let body = self.block(param, nodes);
        let param = if nodes.is_empty() {
            format_ident!("_{param}")
        } else {
            format_ident!("{param}")
        };
        quote!(|#param| { #body })
    }

    // ---- Values ------------------------------------------------------------

    fn color(&mut self, c: [u8; 4]) -> TokenStream {
        let color = self.import("Color");
        let [r, g, b, a] = c.map(Literal::u8_unsuffixed);
        if c[3] == 255 {
            quote!(#color::from_srgb8(#r, #g, #b))
        } else {
            quote!(#color::from_srgba8(#r, #g, #b, #a))
        }
    }

    /// `vec2(w, h)`; an infinite side is `f32::INFINITY` (no limit).
    fn size(&mut self, (w, h): (f64, f64)) -> TokenStream {
        let vec2 = self.import("vec2");
        let side = |v: f64| {
            if v.is_infinite() {
                quote!(f32::INFINITY)
            } else {
                let v = f32_lit(v);
                quote!(#v)
            }
        };
        let (w, h) = (side(w), side(h));
        quote!(#vec2(#w, #h))
    }

    fn shadow(&mut self, s: Shadow) -> TokenStream {
        let shadow = self.import("Shadow");
        let offset = self.size(s.offset);
        let (blur, spread) = (f32_lit(s.blur), f32_lit(s.spread));
        let color = self.color(s.color);
        quote!(#shadow { offset: #offset, blur: #blur, spread: #spread, color: #color })
    }

    fn stroke(&mut self, width: f64, c: [u8; 4]) -> TokenStream {
        let stroke = self.import("Stroke");
        let width = f32_lit(width);
        let color = self.color(c);
        quote!(#stroke::new(#width, #color))
    }

    fn font(&mut self, font: Font) -> TokenStream {
        let style = self.import("TextStyle");
        let ctor = format_ident!("{}", font.family.ctor());
        let size = f32_lit(font.size);
        let mut out = quote!(#style::#ctor(#size));
        if font.weight != Font::REGULAR {
            let weight = Literal::u16_unsuffixed(font.weight);
            out = quote!(#out.weight(#weight));
        }
        if font.bold {
            out = quote!(#out.bold());
        }
        out
    }

    /// `vec![Track::Points(120.0), Track::Fraction(1.0), Track::Auto]`
    fn tracks(&mut self, text: &str) -> TokenStream {
        let track = self.import("Track");
        let tracks = parse_tracks(text)
            .unwrap_or_else(|_| vec![Track::Auto])
            .into_iter()
            .map(|t| match t {
                Track::Points(v) => {
                    let v = f32_lit(v);
                    quote!(#track::Points(#v))
                }
                Track::Fraction(v) => {
                    let v = f32_lit(v);
                    quote!(#track::Fraction(#v))
                }
                Track::Auto => quote!(#track::Auto),
            });
        quote!(vec![#(#tracks),*])
    }

    /// The builder calls `.method(value)` for the node's properties, in
    /// [`builder_methods`] order.
    fn builders(&mut self, node: &Node) -> TokenStream {
        let mut out = TokenStream::new();
        for &(method, key, arg) in builder_methods(node.kind) {
            let Some(value) = node.prop(key) else {
                continue;
            };
            let method = format_ident!("{method}");
            let call = match (arg, value) {
                (Arg::Flag, Value::Bool(true)) => quote!(.#method()),
                (Arg::Set(set), Value::Text(text)) if set == text => quote!(.#method()),
                (Arg::Shadow, Value::Shadow(s)) => {
                    let s = self.shadow(*s);
                    quote!(.#method(#s))
                }
                (Arg::Bool, Value::Bool(b)) => {
                    let init = node.kind.prop(key).and_then(|s| s.init.to_value());
                    if init == Some(Value::Bool(*b)) {
                        continue;
                    }
                    quote!(.#method(#b))
                }
                (Arg::Fill, Value::Sizing(Sizing::Fill)) => quote!(.#method()),
                (Arg::Sizing, Value::Sizing(sizing)) => match sizing {
                    Sizing::Content => {
                        let ty = self.import("Sizing");
                        quote!(.#method(#ty::Content))
                    }
                    Sizing::Points(v) => {
                        let ty = self.import("Sizing");
                        let v = f32_lit(*v);
                        quote!(.#method(#ty::Points(#v)))
                    }
                    Sizing::Fill => continue,
                },
                (Arg::Tracks, Value::Text(text)) => {
                    let tracks = self.tracks(text);
                    quote!(.#method(#tracks))
                }
                (Arg::AxisLabel, Value::Text(text)) => {
                    let axis = self.import("Axis");
                    quote!(.#method(#axis::new().label(#text)))
                }
                (Arg::LineStyle, Value::Text(style)) => {
                    if style == "solid" {
                        continue;
                    }
                    let ty = self.import("LineStyle");
                    let ctor = format_ident!("{style}");
                    quote!(.#method(#ty::#ctor()))
                }
                (Arg::Str, Value::Text(text)) => quote!(.#method(#text)),
                (Arg::Float, v) => match v.as_f64() {
                    Some(v) => {
                        let v = f32_lit(v);
                        quote!(.#method(#v))
                    }
                    None => continue,
                },
                (Arg::Int, Value::Int(v)) => {
                    let v = Literal::usize_unsuffixed((*v).max(0) as usize);
                    quote!(.#method(#v))
                }
                (Arg::Range, Value::Range(min, max)) => {
                    let (min, max) = (f32_lit(*min), f32_lit(*max));
                    quote!(.#method(#min..=#max))
                }
                (Arg::Variant(ty), Value::Text(variant)) => {
                    let ty = self.import(ty);
                    let variant = format_ident!("{variant}");
                    quote!(.#method(#ty::#variant))
                }
                (Arg::Color, Value::Color(c)) => {
                    let c = self.color(*c);
                    quote!(.#method(#c))
                }
                (Arg::Size, Value::Size(w, h)) => {
                    let size = self.size((*w, *h));
                    quote!(.#method(#size))
                }
                (Arg::Stroke, Value::Stroke(w, c)) => {
                    let stroke = self.stroke(*w, *c);
                    quote!(.#method(#stroke))
                }
                (Arg::Font, Value::Font(f)) => {
                    let font = self.font(*f);
                    quote!(.#method(#font))
                }
                _ => continue,
            };
            out.extend(call);
        }
        out
    }

    /// `ui.style_mut().visuals.text = …;` for each content style property
    /// that is set.
    fn content_style(&mut self, ui: &str, props: &BTreeMap<&'static str, Value>) -> TokenStream {
        let ui = format_ident!("{ui}");
        let mut out = TokenStream::new();
        for spec in CONTENT_STYLE {
            let (Some(value), Some(target)) = (props.get(spec.key), content_style_target(spec.key))
            else {
                continue;
            };
            let path = target.split('.').map(|f| format_ident!("{f}"));
            let value = match value {
                Value::Color(c) => self.color(*c),
                Value::Size(w, h) => self.size((*w, *h)),
                _ => continue,
            };
            out.extend(quote!(#ui.style_mut() #(.#path)* = #value;));
        }
        out
    }

    /// `|ui| { … }` for a container's children, starting with its content
    /// style.
    fn styled_closure(&mut self, param: &str, node: &Node) -> TokenStream {
        let style = self.content_style(param, &node.props);
        let body = self.block(param, &node.children);
        let param = if node.children.is_empty() && style.is_empty() {
            format_ident!("_{param}")
        } else {
            format_ident!("{param}")
        };
        quote!(|#param| { #style #body })
    }

    // ---- Widgets -------------------------------------------------------------

    /// A widget added with `ui.add(…)`: its shorthand call when it has one
    /// and no options (`ui.label("…")`), else `ui.add(Widget…)`, or
    /// `ui.add_sized(size, Widget…)` with a fixed size. `None` for other
    /// kinds.
    fn leaf(&mut self, ui: &Ident, node: &Node) -> Option<TokenStream> {
        let text = node.text("text");
        let binding = node.binding().map(|(name, _)| format_ident!("{name}"));
        let mut calls = self.builders(node);
        let fixed = node.prop("fixed_size").and_then(Value::as_size);
        let plain = calls.is_empty() && fixed.is_none();
        let (short, ctor) = match node.kind {
            WidgetKind::Label => (quote!(#ui.label(#text)), {
                let label = self.import_if(!plain, "Label");
                quote!(#label::new(#text))
            }),
            WidgetKind::Heading => {
                // Color or size: a label in the heading style.
                let style = quote!(.style(#ui.style().heading.clone()));
                calls = quote!(#style #calls);
                let label = self.import_if(!plain, "Label");
                (quote!(#ui.heading(#text)), quote!(#label::new(#text)))
            }
            WidgetKind::Hyperlink => {
                let url = node.text("url");
                let link = self.import_if(!plain, "Hyperlink");
                if text.is_empty() {
                    (quote!(#ui.hyperlink(#url)), quote!(#link::new(#url)))
                } else {
                    (
                        quote!(#ui.hyperlink_to(#text, #url)),
                        quote!(#link::from_label_and_url(#text, #url)),
                    )
                }
            }
            WidgetKind::Button => (quote!(#ui.button(#text)), {
                let button = self.import_if(!plain, "Button");
                quote!(#button::new(#text))
            }),
            WidgetKind::Checkbox => (quote!(#ui.checkbox(&mut self.#binding, #text)), {
                let checkbox = self.import_if(!plain, "Checkbox");
                quote!(#checkbox::new(&mut self.#binding, #text))
            }),
            WidgetKind::Separator => (quote!(#ui.separator()), {
                let separator = self.import_if(!plain, "Separator");
                quote!(#separator::new())
            }),
            WidgetKind::Spinner => (quote!(#ui.spinner()), {
                let spinner = self.import_if(!plain, "Spinner");
                quote!(#spinner::new())
            }),
            WidgetKind::TextEdit => {
                let multiline = node.flag("multiline");
                let edit = self.import_if(!plain, "TextEdit");
                if multiline {
                    (
                        quote!(#ui.text_edit_multiline(&mut self.#binding)),
                        quote!(#edit::multiline(&mut self.#binding)),
                    )
                } else {
                    (
                        quote!(#ui.text_edit_singleline(&mut self.#binding)),
                        quote!(#edit::singleline(&mut self.#binding)),
                    )
                }
            }
            WidgetKind::Slider => {
                let slider = self.import("Slider");
                let range = match node.prop("range").and_then(Value::as_range) {
                    Some((min, max)) => {
                        let (min, max) = (f32_lit(min), f32_lit(max));
                        quote!(#min..=#max)
                    }
                    None => quote!(0.0..=1.0),
                };
                let ctor = quote!(#slider::new(&mut self.#binding, #range));
                (quote!(#ui.add(#ctor)), ctor)
            }
            WidgetKind::DragValue => {
                let drag = self.import("DragValue");
                let ctor = quote!(#drag::new(&mut self.#binding));
                (quote!(#ui.add(#ctor)), ctor)
            }
            WidgetKind::ProgressBar => {
                let bar = self.import("ProgressBar");
                let ctor = quote!(#bar::new(self.#binding));
                (quote!(#ui.add(#ctor)), ctor)
            }
            WidgetKind::SearchField => {
                let search = self.import("SearchField");
                let ctor = quote!(#search::new(&mut self.#binding));
                (quote!(#ui.add(#ctor)), ctor)
            }
            WidgetKind::TimePicker => {
                let picker = self.import("TimePicker");
                let ctor = quote!(#picker::new(&mut self.#binding.0, &mut self.#binding.1));
                (quote!(#ui.add(#ctor)), ctor)
            }
            WidgetKind::ColorPicker => {
                let picker = self.import("ColorPicker");
                let ctor = quote!(#picker::new(&mut self.#binding));
                (quote!(#ui.add(#ctor)), ctor)
            }
            WidgetKind::DatePicker => {
                let picker = self.import("DatePicker");
                let ctor = quote!(#picker::new(&mut self.#binding));
                (quote!(#ui.add(#ctor)), ctor)
            }
            _ => return None,
        };
        Some(match fixed {
            _ if plain => short,
            Some(size) => {
                let size = self.size(size);
                quote!(#ui.add_sized(#size, #ctor #calls))
            }
            None => quote!(#ui.add(#ctor #calls)),
        })
    }

    fn import_if(&mut self, needed: bool, name: &'static str) -> TokenStream {
        if needed {
            self.import(name)
        } else {
            let ident = format_ident!("{name}");
            quote!(#ident)
        }
    }

    fn node(&mut self, ui: &str, node: &Node) -> TokenStream {
        let ui = format_ident!("{ui}");
        if let Some(expr) = self.leaf(&ui, node) {
            let on_click = node.text("on_click");
            return if node.kind == WidgetKind::Button && !on_click.trim().is_empty() {
                let body = self.raw(on_click);
                quote!(if #expr.clicked() { #body })
            } else {
                quote!(#expr;)
            };
        }
        let text = node.text("text");
        let binding = node.binding().map(|(name, _)| format_ident!("{name}"));
        match node.kind {
            WidgetKind::Space => {
                let amount = float(node, "amount").unwrap_or_else(|| Literal::f32_unsuffixed(0.0));
                quote!(#ui.add_space(#amount);)
            }
            WidgetKind::RadioValue | WidgetKind::SelectableValue => {
                let method = if node.kind == WidgetKind::RadioValue {
                    format_ident!("radio_value")
                } else {
                    format_ident!("selectable_value")
                };
                let value = int(node, "value").unwrap_or_else(|| Literal::usize_unsuffixed(0));
                let calls = self.builders(node);
                if calls.is_empty() {
                    quote!(#ui.#method(&mut self.#binding, #value, #text);)
                } else {
                    // What `radio_value` does, with a styled widget.
                    let widget = self.import(if node.kind == WidgetKind::RadioValue {
                        "RadioButton"
                    } else {
                        "SelectableLabel"
                    });
                    quote! {
                        if #ui.add(#widget::new(self.#binding == #value, #text) #calls).clicked() {
                            self.#binding = #value;
                        }
                    }
                }
            }
            WidgetKind::ComboBox => {
                let combo = self.import("ComboBox");
                let label = node.text("label");
                let items = node.prop("items").and_then(Value::as_items).unwrap_or(&[]);
                let calls = self.builders(node);
                // The binding must appear even without items, so the
                // parser can read it back.
                let selected = if items.is_empty() {
                    quote!(self.#binding.to_string())
                } else {
                    let last = Literal::usize_unsuffixed(items.len() - 1);
                    quote!([#(#items),*][self.#binding.min(#last)])
                };
                let options = items.iter().enumerate().map(|(i, item)| {
                    let i = Literal::usize_unsuffixed(i);
                    quote!(ui.selectable_value(&mut self.#binding, #i, #item);)
                });
                let param = if items.is_empty() {
                    format_ident!("_ui")
                } else {
                    format_ident!("ui")
                };
                quote!(#combo::from_label(#label) #calls .selected_text(#selected).show_ui(#ui, |#param| { #(#options)* });)
            }
            WidgetKind::Grid => {
                let grid = self.import("Grid");
                let id = node.text("id");
                let calls = self.builders(node);
                let body = self.styled_closure("ui", node);
                quote!(#grid::new(#id) #calls .show(#ui, #body);)
            }
            WidgetKind::EndRow => quote!(#ui.end_row();),
            WidgetKind::GridCell => {
                let index = |key| {
                    let v = node.prop(key).and_then(Value::as_int);
                    v.map(|v| v.clamp(0, i64::from(u16::MAX)) as u16)
                };
                let columns = index("column_span").unwrap_or(1).max(1);
                let rows = index("row_span").unwrap_or(1).max(1);
                let [columns_lit, rows_lit] = [columns, rows].map(Literal::u16_unsuffixed);
                let body = self.styled_closure("ui", node);
                match index("column") {
                    Some(column) => {
                        let cell = self.import("GridCell");
                        let row = index("row").unwrap_or(0);
                        let [column, row] = [column, row].map(Literal::u16_unsuffixed);
                        let mut chain = quote!(#cell::at(#column, #row));
                        if (columns, rows) != (1, 1) {
                            chain = quote!(#chain.span(#columns_lit, #rows_lit));
                        }
                        quote!(#ui.grid_cell(#chain, #body);)
                    }
                    None => quote!(#ui.grid_span(#columns_lit, #rows_lit, #body);),
                }
            }
            WidgetKind::Collapsing => {
                let calls = self.builders(node);
                let body = self.styled_closure("ui", node);
                if calls.is_empty() {
                    quote!(#ui.collapsing(#text, #body);)
                } else {
                    let header = self.import("CollapsingHeader");
                    quote!(#header::new(#text) #calls .show(#ui, #body);)
                }
            }
            WidgetKind::Stack => {
                let calls = self.builders(node);
                let body = self.styled_closure("ui", node);
                // Without options, the short forms.
                match node.text("direction") {
                    "column" if calls.is_empty() => quote!(#ui.vertical(#body);),
                    "row" if calls.is_empty() => quote!(#ui.horizontal(#body);),
                    direction => {
                        let stack = self.import("Stack");
                        let direction = format_ident!("{direction}");
                        quote!(#stack::#direction() #calls .show(#ui, #body);)
                    }
                }
            }
            WidgetKind::StackItem => {
                let item = self.import("StackItem");
                let calls = self.builders(node);
                let body = self.styled_closure("ui", node);
                quote!(#ui.stack_item(#item::new() #calls, #body);)
            }
            WidgetKind::Panel => {
                let panel = self.import("Panel");
                let side = format_ident!("{}", node.text("side"));
                let id = node.text("id");
                let calls = self.builders(node);
                let body = self.styled_closure("ui", node);
                quote!(#panel::#side(#id) #calls .show_inside(#ui, #body);)
            }
            WidgetKind::CentralPanel => {
                let panel = self.import("CentralPanel");
                let calls = self.builders(node);
                let body = self.styled_closure("ui", node);
                quote!(#panel::default() #calls .show_inside(#ui, #body);)
            }
            WidgetKind::ScrollArea => {
                let area = self.import("ScrollArea");
                let direction = format_ident!("{}", node.text("direction"));
                let calls = self.builders(node);
                let body = self.styled_closure("ui", node);
                quote!(#area::#direction() #calls .show(#ui, #body);)
            }
            WidgetKind::Plot => {
                let plot = self.import("Plot");
                let id = node.text("id");
                let calls = self.builders(node);
                let body = self.closure("plot", &node.children);
                quote!(#plot::new(#id) #calls .show(#ui, #body);)
            }
            WidgetKind::PlotLine | WidgetKind::PlotPoints => {
                let (method, ty) = if node.kind == WidgetKind::PlotLine {
                    (format_ident!("line"), self.import("Line"))
                } else {
                    (format_ident!("points"), self.import("Points"))
                };
                let calls = self.builders(node);
                quote!(#ui.#method(#ty::new(&self.#binding) #calls);)
            }
            WidgetKind::PlotHLine | WidgetKind::PlotVLine => {
                let (method, ty) = if node.kind == WidgetKind::PlotHLine {
                    (format_ident!("hline"), self.import("HLine"))
                } else {
                    (format_ident!("vline"), self.import("VLine"))
                };
                let value = float(node, "value").unwrap_or_else(|| Literal::f32_unsuffixed(0.0));
                let calls = self.builders(node);
                quote!(#ui.#method(#ty::new(#value) #calls);)
            }
            WidgetKind::PieChart => {
                let pie = self.import("PieChart");
                let calls = self.builders(node);
                quote!(#pie::new(self.#binding.clone()) #calls .show(#ui);)
            }
            WidgetKind::RawCode => self.raw(node.text("code")),
            // Drawn by `leaf`.
            _ => TokenStream::new(),
        }
    }
}

fn f32_lit(v: f64) -> Literal {
    Literal::f32_unsuffixed(v as f32)
}

fn float(node: &Node, key: &str) -> Option<Literal> {
    let v = node.prop(key)?.as_f64()?;
    Some(Literal::f32_unsuffixed(v as f32))
}

fn int(node: &Node, key: &str) -> Option<Literal> {
    let v = node.prop(key)?.as_int()?;
    Some(Literal::usize_unsuffixed(v.max(0) as usize))
}

/// Whether `code` contains `name` as a whole identifier.
pub(crate) fn mentions(code: &str, name: &str) -> bool {
    let is_ident = |c: char| c.is_alphanumeric() || c == '_';
    code.match_indices(name).any(|(i, _)| {
        !code[..i].ends_with(is_ident) && !code[i + name.len()..].starts_with(is_ident)
    })
}

/// Indents every non-empty line of `code` by `indent`.
fn indent(code: &str, indent: &str) -> String {
    code.trim_matches('\n')
        .lines()
        .map(|line| {
            if line.trim().is_empty() {
                String::new()
            } else {
                format!("{indent}{line}")
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
}

/// Replaces each placeholder line `__rtk_raw!(n);` with `raw[n]`, indented
/// like the placeholder.
fn splice_raw(formatted: &str, raw: &[String]) -> String {
    let mut out = String::with_capacity(formatted.len());
    for line in formatted.lines() {
        let trimmed = line.trim_start();
        let index = trimmed
            .strip_prefix("__rtk_raw!(")
            .and_then(|rest| rest.strip_suffix(");"))
            .and_then(|n| n.parse::<usize>().ok());
        match index.and_then(|i| raw.get(i)) {
            Some(code) => {
                let block = indent(code, &line[..line.len() - trimmed.len()]);
                if !block.is_empty() {
                    out.push_str(&block);
                    out.push('\n');
                }
            }
            None => {
                out.push_str(line);
                out.push('\n');
            }
        }
    }
    out
}

/// Puts a blank line between the items of the impl block (prettyplease
/// writes them one after the other): before each doc comment at item
/// indentation that follows the end of another item.
fn separate_items(code: &str) -> String {
    let mut out = String::with_capacity(code.len());
    let mut prev = "";
    for line in code.lines() {
        let item_doc = line.starts_with("    ///") && !line.starts_with("     ");
        let prev_item_line =
            prev.starts_with("    ") && !prev.starts_with("     ") && !prev.starts_with("    ///");
        if item_doc && prev_item_line {
            out.push('\n');
        }
        out.push_str(line);
        out.push('\n');
        prev = line;
    }
    out
}

/// The whole `<view>.rs` file.
pub fn view_code(view: &View) -> String {
    let mut g = Gen {
        raw: Vec::new(),
        imports: BTreeSet::new(),
    };
    let style = g.content_style("ui", &view.style);
    let body = g.block("ui", &view.nodes);
    let body = quote!(#style #body);
    g.imports
        .extend(["Ui", "UiRoot", "Window", "WindowOptions"]);
    // Free code may use managed names that no node needs.
    let free_code = g
        .raw
        .iter()
        .chain(&view.extra_methods)
        .chain(&view.extra_items);
    for code in free_code {
        for name in MANAGED_IMPORTS {
            if mentions(code, name) {
                g.imports.insert(name);
            }
        }
    }
    let (fields, _) = view.fields();
    for field in &fields {
        match field.ty {
            FieldType::Color => g.imports.insert("Color"),
            FieldType::Date => g.imports.insert("Date"),
            _ => false,
        };
    }
    let ui_param = if view.nodes.is_empty() && view.style.is_empty() {
        format_ident!("_ui")
    } else {
        format_ident!("ui")
    };
    let struct_name = format_ident!("{}", view.struct_name());
    let window = &view.window;
    let title = &window.title;
    let (width, height) = (
        Literal::f32_unsuffixed(window.width),
        Literal::f32_unsuffixed(window.height),
    );
    let resizable = window.resizable;
    let limit = |size: Option<(f32, f32)>| match size {
        Some((w, h)) => {
            let (w, h) = (Literal::f32_unsuffixed(w), Literal::f32_unsuffixed(h));
            quote!(Some((#w, #h)))
        }
        None => quote!(None),
    };
    let (min_size, max_size) = (limit(window.min_size), limit(window.max_size));
    let impl_block = quote! {
        impl #struct_name {
            /// Window title.
            pub const TITLE: &'static str = #title;
            /// Window size in points: width, height.
            pub const SIZE: (f32, f32) = (#width, #height);
            /// Whether the user can resize the window.
            pub const RESIZABLE: bool = #resizable;
            /// Smallest size the user can resize the window to.
            pub const MIN_SIZE: Option<(f32, f32)> = #min_size;
            /// Largest size the user can resize the window to.
            pub const MAX_SIZE: Option<(f32, f32)> = #max_size;

            /// Options to open the view as the app's native window.
            pub fn window_options() -> WindowOptions {
                let points = |(w, h): (f32, f32)| (f64::from(w), f64::from(h));
                WindowOptions {
                    title: Self::TITLE.to_owned(),
                    inner_size: points(Self::SIZE),
                    resizable: Self::RESIZABLE,
                    min_inner_size: Self::MIN_SIZE.map(points),
                    max_inner_size: Self::MAX_SIZE.map(points),
                    ..Default::default()
                }
            }

            /// Shows the view in a window inside the app.
            pub fn show_window(&mut self, root: &mut impl UiRoot) {
                Window::new(Self::TITLE)
                    .default_width(Self::SIZE.0)
                    .default_height(Self::SIZE.1)
                    .resizable(Self::RESIZABLE)
                    .show(root, |ui| self.show(ui));
            }

            /// Draws the view.
            pub fn show(&mut self, #ui_param: &mut Ui<'_>) {
                #body
            }
        }
    };

    let mut imports: BTreeSet<&str> = g.imports.iter().copied().collect();
    imports.extend(view.extra_imports.iter().map(String::as_str));
    let imports: Vec<_> = imports
        .into_iter()
        .map(|name| format_ident!("{name}"))
        .collect();
    let use_line = match imports.as_slice() {
        [one] => quote!(use rustroke::#one;),
        _ => quote!(use rustroke::{#(#imports),*};),
    };

    let file: syn::File =
        syn::parse2(quote!(#use_line #impl_block)).expect("generated code is valid Rust");
    let formatted = prettyplease::unparse(&file);
    let impl_start = formatted
        .find("\nimpl ")
        .expect("use line, then the impl block");
    let (use_part, impl_part) = formatted.split_at(impl_start + 1);
    let mut impl_part = separate_items(&splice_raw(impl_part, &g.raw));
    if !view.extra_methods.is_empty() {
        // Hand-written methods go before the closing brace of the impl.
        let end = impl_part.trim_end().len() - 1;
        impl_part.truncate(end);
        for method in &view.extra_methods {
            impl_part.push('\n');
            impl_part.push_str(&indent(method, "    "));
            impl_part.push('\n');
        }
        impl_part.push_str("}\n");
    }

    let mut out = String::new();
    out.push_str(&header());
    out.push('\n');
    out.push_str(use_part.trim_end());
    out.push_str("\n\n");
    out.push_str(&format!("#[derive({})]\n", view.derives.join(", ")));
    if fields.is_empty() && view.extra_fields.is_empty() {
        out.push_str(&format!("pub struct {} {{}}\n\n", view.struct_name()));
    } else {
        out.push_str(&format!("pub struct {} {{\n", view.struct_name()));
    }
    for field in &fields {
        out.push_str(&format!(
            "    pub {}: {},\n",
            field.name,
            field.ty.rust_name()
        ));
    }
    for field in &view.extra_fields {
        out.push_str(&indent(field.code.trim_end().trim_end_matches(','), "    "));
        out.push_str(",\n");
    }
    if !fields.is_empty() || !view.extra_fields.is_empty() {
        out.push_str("}\n\n");
    }
    out.push_str(&impl_part);
    for item in &view.extra_items {
        out.push('\n');
        out.push_str(item.trim_matches('\n'));
        out.push('\n');
    }
    out
}

/// `mod.rs`: one `pub mod` per view, in project order.
pub fn mod_code(project: &Project) -> String {
    let mut out = format!(
        "// Views generated by Rustroke Toolkit {} for rustroke {RUSTROKE_VERSION}.\n\n",
        env!("CARGO_PKG_VERSION")
    );
    for view in &project.views {
        out.push_str(&format!("pub mod {};\n", view.name));
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::kind::WidgetKind as K;

    #[test]
    fn rustroke_version_matches_the_dependency() {
        let manifest = include_str!("../../../Cargo.toml");
        let line = manifest
            .lines()
            .find(|l| l.starts_with("rustroke = "))
            .expect("rustroke dependency");
        assert!(
            line.contains(&format!("version = \"{RUSTROKE_VERSION}.")),
            "RUSTROKE_VERSION ({RUSTROKE_VERSION}) differs from {line}"
        );
    }

    #[test]
    fn empty_view() {
        let view = View::new("empty");
        let code = view_code(&view);
        assert!(code.starts_with(&format!("{}\nuse rustroke::{{Ui, UiRoot, Window, WindowOptions}};\n\n#[derive(Debug, Default)]\npub struct Empty {{}}\n", header())), "{code}");
        assert!(
            code.contains("pub const TITLE: &'static str = \"Empty\";"),
            "{code}"
        );
        assert!(
            code.contains("pub const SIZE: (f32, f32) = (480.0, 360.0);"),
            "{code}"
        );
        assert!(code.contains("pub const RESIZABLE: bool = true;"), "{code}");
        assert!(
            code.ends_with(
                "    /// Draws the view.\n    pub fn show(&mut self, _ui: &mut Ui<'_>) {}\n}\n"
            ),
            "{code}"
        );
    }

    #[test]
    fn raw_code_keeps_comments_and_indentation() {
        let mut view = View::new("raw");
        let mut button = view.create(K::Button);
        button.props.insert(
            "on_click",
            Value::Text("// Count clicks.\nself.clicks += 1;\nif self.clicks > 3 {\n    self.clicks = 0;\n}".into()),
        );
        let mut horizontal = view.create(K::Stack);
        horizontal
            .props
            .insert("direction", Value::Text("row".into()));
        horizontal.children.push(button);
        view.insert(None, 0, horizontal).unwrap();
        let code = view_code(&view);
        assert!(
            code.contains(
                "            if ui.button(\"Button\").clicked() {\n                // Count clicks.\n                self.clicks += 1;\n                if self.clicks > 3 {\n                    self.clicks = 0;\n                }\n            }\n"
            ),
            "{code}"
        );
    }
}
