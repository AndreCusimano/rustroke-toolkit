//! Model → Rust code.
//!
//! The code is built with `quote` and formatted with `prettyplease`. Free
//! code (raw nodes, button handlers, hand-written fields, methods and items)
//! must keep its comments and layout, which a syntax tree would lose, so it
//! goes in as a placeholder statement `__rtk_raw!(n);` that is replaced
//! with the original text, re-indented, after formatting.

use std::collections::{BTreeMap, BTreeSet};

use proc_macro2::{Ident, Literal, TokenStream};
use quote::{format_ident, quote};

use crate::builders::{Arg, builder_methods};
use crate::kind::{CONTENT_STYLE, WidgetKind, content_style_target};
use crate::model::{Node, Project, View};
use crate::value::{FieldType, Font, Shadow, Sizing, Track, Value, parse_tracks};

/// The rustroke version the generated code targets (`major.minor`). The
/// toolkit's own major version changes when this does.
pub const RUSTROKE_VERSION: &str = "0.20";

/// Start of the first line of every generated view file; the parser drops
/// lines starting with it, whatever toolkit version wrote them.
pub const HEADER_PREFIX: &str = "// View generated by Rustroke Toolkit";

/// First line of every generated view file, with the toolkit and rustroke
/// versions.
pub fn header() -> String {
    format!(
        "{HEADER_PREFIX} {} for rustroke {RUSTROKE_VERSION} (https://crates.io/crates/rustroke).",
        env!("CARGO_PKG_VERSION")
    )
}

